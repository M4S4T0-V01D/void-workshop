// Generates the phone's themes from the desktop's (src/themes.ts), so both apps share one list.
// From the repo root:  node --experimental-strip-types remote/android/art/gen_themes.mjs
// then, in remote/android:  python3 art/gen_icon.py   (one launcher icon per theme)
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.cwd();
const { BUILTIN_THEMES } = await import(pathToFileURL(path.join(root, 'src/themes.ts')).href);

fs.writeFileSync(path.join(root, 'remote/android/art/themes.json'), JSON.stringify(BUILTIN_THEMES, null, 2) + '\n');

const kt = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;
const lines = BUILTIN_THEMES.map((t) => {
  const c = t.colors;
  return (
    `    Palette("${t.id}", "${t.name}", light = ${t.mode === 'light'}, bg = ${kt(c.bg)}, panel = ${kt(c.panel)}, ` +
    `panelAlt = ${kt(c.panelAlt)}, border = ${kt(c.border)}, text = ${kt(c.text)}, dim = ${kt(c.textDim)}, accent = ${kt(c.accent)}, ` +
    `accent2 = ${kt(c.accent2)}, ok = ${kt(c.success)}, warn = ${kt(c.warning)}, bad = ${kt(c.danger)}),`
  );
});
fs.writeFileSync(
  path.join(root, 'remote/android/app/src/main/java/dev/m4s4t0/voidportal/ui/BuiltinThemes.kt'),
  `package dev.m4s4t0.voidportal.ui

import androidx.compose.ui.graphics.Color

// Generated by remote/android/art/gen_themes.mjs from the desktop's src/themes.ts. Do not edit.
val BUILTIN_THEMES = listOf(
${lines.join('\n')}
)
`,
);
console.log(`${BUILTIN_THEMES.length} themes: ${BUILTIN_THEMES.map((t) => t.id).join(', ')}`);
